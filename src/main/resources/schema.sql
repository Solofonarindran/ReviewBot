-- ReviewBot : schéma HSQLDB (7 tables). Exécuté à chaque démarrage, sans effet si les tables existent.

CREATE TABLE IF NOT EXISTS repository (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform                  VARCHAR(20)  NOT NULL CHECK (platform IN ('GITHUB','GITLAB','BITBUCKET')),
    full_name                 VARCHAR(255) NOT NULL,
    clone_url                 VARCHAR(500) NOT NULL,
    api_token_encrypted       VARCHAR(1000),
    webhook_secret_encrypted  VARCHAR(1000),
    enabled                   BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at                TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at                TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_repository UNIQUE (platform, full_name)
);

CREATE TABLE IF NOT EXISTS review (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id            BIGINT       NOT NULL,
    pr_number                VARCHAR(50)  NOT NULL,
    pr_title                 VARCHAR(500),
    pr_author                VARCHAR(255),
    source_branch            VARCHAR(255),
    target_branch            VARCHAR(255),
    head_commit_sha          VARCHAR(64)  NOT NULL,
    status                   VARCHAR(20)  NOT NULL CHECK (status IN ('QUEUED','RUNNING','DONE','FAILED','CANCELLED')),
    verdict                  VARCHAR(20)  CHECK (verdict IN ('APPROVED','TO_FIX','BLOCKING')),
    blocking_count           INT          DEFAULT 0 NOT NULL,
    major_count              INT          DEFAULT 0 NOT NULL,
    minor_count              INT          DEFAULT 0 NOT NULL,
    coverage_changed_lines   DECIMAL(5,2),
    error_message            CLOB,
    config_snapshot          CLOB,
    global_comment_ref       VARCHAR(255),
    queued_at                TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    started_at               TIMESTAMP,
    finished_at              TIMESTAMP,
    CONSTRAINT fk_review_repository FOREIGN KEY (repository_id) REFERENCES repository (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS job_queue (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id     BIGINT       NOT NULL,
    state         VARCHAR(20)  NOT NULL CHECK (state IN ('QUEUED','RUNNING','DONE','FAILED')),
    attempts      INT          DEFAULT 0 NOT NULL,
    last_error    CLOB,
    locked_by     VARCHAR(100),
    locked_until  TIMESTAMP,
    created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_job_review FOREIGN KEY (review_id) REFERENCES review (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS analysis_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id       BIGINT       NOT NULL,
    tool            VARCHAR(20)  NOT NULL CHECK (tool IN ('JAVADOC','JUNIT','CHECKSTYLE','PMD','SPOTBUGS','ERRORPRONE','JACOCO','LLM')),
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('OK','FAILED','SKIPPED','TIMEOUT')),
    findings_count  INT          DEFAULT 0 NOT NULL,
    duration_ms     INT,
    error_message   CLOB,
    started_at      TIMESTAMP,
    finished_at     TIMESTAMP,
    CONSTRAINT fk_run_review FOREIGN KEY (review_id) REFERENCES review (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS finding (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id        BIGINT       NOT NULL,
    analysis_run_id  BIGINT,
    merged_into_id   BIGINT,
    source           VARCHAR(20)  NOT NULL,
    rule_id          VARCHAR(200),
    category         VARCHAR(20)  NOT NULL CHECK (category IN ('BUG','STYLE','SECURITY','COVERAGE','DOC','CODE')),
    severity         VARCHAR(20)  NOT NULL CHECK (severity IN ('BLOCKING','MAJOR','MINOR','INFO')),
    file_path        VARCHAR(1000),
    line_start       INT,
    line_end         INT,
    title            VARCHAR(500) NOT NULL,
    message          CLOB,
    suggestion       CLOB,
    in_diff          BOOLEAN      DEFAULT FALSE NOT NULL,
    fingerprint      VARCHAR(128) NOT NULL,
    created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_finding_review FOREIGN KEY (review_id) REFERENCES review (id) ON DELETE CASCADE,
    CONSTRAINT fk_finding_run    FOREIGN KEY (analysis_run_id) REFERENCES analysis_run (id) ON DELETE SET NULL,
    CONSTRAINT fk_finding_merged FOREIGN KEY (merged_into_id) REFERENCES finding (id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS finding_flag (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id  BIGINT       NOT NULL,
    flagged_by  VARCHAR(255) NOT NULL,
    reason      VARCHAR(1000),
    flagged_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_flag_finding UNIQUE (finding_id),
    CONSTRAINT fk_flag_finding FOREIGN KEY (finding_id) REFERENCES finding (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS posted_comment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id            BIGINT       NOT NULL,
    finding_id           BIGINT,
    kind                 VARCHAR(10)  NOT NULL CHECK (kind IN ('GLOBAL','INLINE')),
    platform_comment_id  VARCHAR(255),
    file_path            VARCHAR(1000),
    line                 INT,
    state                VARCHAR(20)  NOT NULL CHECK (state IN ('POSTED','RESOLVED','DELETED')),
    posted_at            TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_comment_review  FOREIGN KEY (review_id)  REFERENCES review (id)  ON DELETE CASCADE,
    CONSTRAINT fk_comment_finding FOREIGN KEY (finding_id) REFERENCES finding (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_review_repo      ON review (repository_id, queued_at);
CREATE INDEX IF NOT EXISTS idx_review_status    ON review (status);
CREATE INDEX IF NOT EXISTS idx_job_state        ON job_queue (state, created_at);
CREATE INDEX IF NOT EXISTS idx_run_review       ON analysis_run (review_id);
CREATE INDEX IF NOT EXISTS idx_finding_review   ON finding (review_id);
CREATE INDEX IF NOT EXISTS idx_finding_filter   ON finding (category, severity);
CREATE INDEX IF NOT EXISTS idx_finding_print    ON finding (fingerprint);
CREATE INDEX IF NOT EXISTS idx_comment_review   ON posted_comment (review_id);
